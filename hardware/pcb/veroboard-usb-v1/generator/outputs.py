"""Write veroboard-usb-v1's parts lists, assembly sheet and output manifest. Stdlib only.

    outputs.py bom <board_dir>          BOM.md and <name>-bom.csv
    outputs.py assembly <board_dir>     ASSEMBLY.md: cuts, links, every part's holes, build order, box sizes
    outputs.py manifest <board_dir>     outputs.sha256

build.sh calls these in order.
"""
import csv
import hashlib
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import design as D  # noqa: E402
import layout as L  # noqa: E402
import vero as V  # noqa: E402

N = D.PROJECT
MANIFEST_SKIP = {'outputs.sha256', 'README.md'}
PKG = {'R0207': 'Axial 0207, flat, 10.16 mm or more', 'DO35': 'DO-35', 'DO15': 'DO-15', 'FG26': 'Radial, 5 mm',
       'module': 'Module, 2 x 6 pins', 'MPT4': 'Terminal block, 4-way, 2.54 mm', 'MPT6': 'Terminal block, 6-way, 2.54 mm'}


def key(ref):
    m = re.match(r'([A-Z]+)(\d+)', ref)
    return m.group(1), int(m.group(2))


def bom_rows():
    groups = {}
    for ref, (kind, value, _p) in D.PARTS.items():
        mf, mpn, code, desc = D.BOM[ref]
        groups.setdefault((mpn, value, kind), []).append(ref)
    rows = []
    for (mpn, value, kind), refs in groups.items():
        refs.sort(key=key)
        mf, _m, code, desc = D.BOM[refs[0]]
        rows.append((refs, len(refs), value, PKG[kind], mf, mpn, code, desc))
    order = {'J': 0, 'U': 1, 'R': 3, 'C': 4, 'D': 5}
    rows.sort(key=lambda r: (order.get(key(r[0][0])[0], 9), key(r[0][0])[1]))
    return rows


def cell(s):
    return str(s).replace('|', '\\|')


def write_bom(board_dir):
    rows = bom_rows()
    with open(os.path.join(board_dir, f'{N}-bom.csv'), 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f, lineterminator='\n')
        w.writerow(['References', 'Qty', 'Value', 'Package', 'Manufacturer', 'MPN', 'Digi-Key UK', 'Description'])
        for r in rows:
            w.writerow([' '.join(r[0])] + list(r[1:]))
        for item, qty, mf, mpn, code, notes in D.EXTRAS:
            w.writerow(['', qty, item, '', mf, mpn, code, notes])
    md = [f'# {N}: parts list', '',
          f'Every part for the {N} stripboard, its cables and its wiring. The same list is in `{N}-bom.csv`.', '',
          'Generated by `generator/outputs.py` from `generator/design.py`; edit that, not this file, then run '
          '`build.sh`. Part numbers and sizes were checked against the makers\' datasheets and Digi-Key UK on '
          f'{D.DATE}; where no order code is given, order by the manufacturer part number.', '',
          '## On the board', '',
          '| Ref | Qty | Value | Package | Manufacturer | MPN | Digi-Key UK | Notes |', '|---|---:|---|---|---|---|---|---|']
    for refs, qty, value, pkg, mf, mpn, code, desc in rows:
        md.append('| ' + ' | '.join(cell(c) for c in (', '.join(refs), qty, value, pkg, mf, f'`{mpn}`', code or '-', desc)) + ' |')
    md += ['', '## Board, wire and cables (not on the board)', '',
           '| Item | Qty | Manufacturer | MPN | Digi-Key UK | Notes |', '|---|---:|---|---|---|---|']
    for item, qty, mf, mpn, code, notes in D.EXTRAS:
        md.append('| ' + ' | '.join(cell(c) for c in (item, qty, mf or '-', f'`{mpn}`', code or '-', notes)) + ' |')
    md += ['', '## Terminal blocks', '']
    for ref, title, use in D.PINOUTS:
        md += [f'**{ref}, {title}**, pin 1 at the top of the layout drawing', '', '| Pin | Net | Wire to |', '|---:|---|---|']
        pins = D.PARTS[ref][2]
        for pin in sorted(pins, key=int):
            md.append(f'| {pin} | {pins[pin]} | {use[pin]} |')
        md.append('')
    md += ['**Display cable** (J3 to the display\'s 8-way case socket, left to right seen from the back):', '',
           '| Case label | Net | J3 pin |', '|---|---|---|']
    for label, net in D.DISPLAY_END:
        pins = [p for p, n in D.PARTS['J3'][2].items() if n == net]
        md.append(f'| {label} | {net or "-"} | {", ".join(sorted(pins, key=int)) or "not connected"} |')
    md += ['', 'Leave the display\'s 5V pin unconnected: it carries the display\'s USB-C supply, and this board doesn\'t use it.']
    with open(os.path.join(board_dir, 'BOM.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(md) + '\n')


def hole(h):
    return f'{h[0]},{h[1]}'


def write_assembly(board_dir):
    a = V.analyse()
    if a['problems']:
        raise SystemExit('layout problems:\n' + '\n'.join(a['problems']))
    w, h = V.size_mm()
    P = D.PITCH
    md = [f'# {N}: assembly sheet', '',
          'Generated by `generator/outputs.py` from `generator/layout.py`; edit that, not this file, then run `build.sh`. '
          'Holes are written column,strip: columns are counted along the strips from the left and strips from the top, '
          'with the board component side up as in `renders/layout.svg`.', '',
          '## Board', '',
          f'- **{L.W} holes along the strips by {L.H} strips.** Cut the stripboard along the next line of holes outside '
          f'that (column 0 and {L.W + 1}, strip 0 and {L.H + 1}) and file the edges smooth: '
          f'**{w:.1f} x {h:.1f} mm**.',
          f'- **{len(L.CUTS)} track cuts and {len(L.LINKS)} wire links.**', '',
          '## 1. Track cuts (copper side)', '',
          'Cut each strip at the hole listed, with a spot-face cutter or a 3.5 mm drill turned by hand, until no copper '
          'bridges the hole. The copper side is mirrored: column 1 is on the **right** when the board is turned over.', '',
          '| Strip | Columns |', '|---:|---|']
    by_strip = {}
    for c, s in sorted(L.CUTS):
        by_strip.setdefault(s, []).append(c)
    for s in sorted(by_strip):
        md.append(f'| {s} | {", ".join(str(c) for c in by_strip[s])} |')
    md += ['', '## 2. Wire links (component side)', '',
           'Tinned copper wire, flat on the board. L1-L5 lie under the module: fit them before it.', '',
           '| Link | From | To | Joins |', '|---|---|---|---|']
    for i, (p, q) in enumerate(L.LINKS):
        net = a['segment_net'][V.segment_of(p, a['cuts'])]
        md.append(f'| L{i + 1} | {hole(p)} | {hole(q)} | {net} |')
    md += ['', '## 3. Parts, lowest first', '',
           'Resistors lie flat at the spacing given (Vishay asks for at least 10.0 mm between an MBB0207\'s leads). '
           'Each diode\'s band (cathode) goes to the hole marked K.', '',
           '| Ref | Value | Holes | Notes |', '|---|---|---|---|']
    order = {'R0207': 0, 'DO35': 1, 'DO15': 2, 'FG26': 3, 'MPT4': 5, 'MPT6': 5, 'module': 6}
    for ref in sorted(D.PARTS, key=lambda r: (order[D.PARTS[r][0]], key(r))):
        kind, value, pmap = D.PARTS[ref]
        if kind == 'module':
            c, s = L.MODULE_AT['col'], L.MODULE_AT['strip']
            md.append(f'| {ref} | {value} | VIN..ALRT down {c},{s}-{c},{s + 5}; A+..A- down {c + 5},{s}-{c + 5},{s + 5} | '
                      'Chip side up. Solder its header pins straight into the stripboard; never socket it (#39) |')
        elif kind.startswith('MPT'):
            hp = V.block_pins(ref)
            side = L.BLOCKS[ref][2]
            md.append(f'| {ref} | {value} | pin 1 at {hole(hp["1"])} to pin {len(hp)} at {hole(hp[str(len(hp))])} | '
                      f'Wire entries face the {side} end |')
        else:
            p1, p2 = a['pins'][(ref, '1')], a['pins'][(ref, '2')]
            span = abs(p1[0] - p2[0]) + abs(p1[1] - p2[1])
            if kind in ('DO35', 'DO15'):
                holes = f'K {hole(p1)}, A {hole(p2)}'
            else:
                holes = f'{hole(p1)} and {hole(p2)}'
            way = 'along strip ' + str(p1[1]) if p1[1] == p2[1] else 'across the strips'
            md.append(f'| {ref} | {value} | {holes} | {way}, {span * P:.2f} mm |')
    md += ['', '## 4. Checks before power', '',
           '- Under a magnifier, check every cut is clean and no solder bridges two strips.',
           '- With a meter on continuity, check each net joins only its own holes:',
           '']
    for net, members in sorted(D.nets().items()):
        holes_ = sorted({a['pins'][m] for m in members})
        md.append(f'  - **{net}:** ' + ', '.join(f'{r}.{p} ({hole(a["pins"][(r, p)])})' for r, p in sorted(members, key=lambda m: (key(m[0]), m[1]))))
    md += ['', '- And that +3V3, GND, SENDER, SENSE, SCL and SDA don\'t join each other.', '',
           '## Box', '',
           f'- **Board:** {w:.1f} x {h:.1f} mm, 1.6 mm thick. Hold it by its two long edges in slots in the box sides '
           '(about 1 mm deep): nothing on the board comes within 1 mm of those edges.']
    for ref in ('J3', 'J2'):
        r = a['bodies'][ref]
        side = L.BLOCKS[ref][2]
        md.append(f'- **{ref} opening, {side} end:** {r[1]:.1f} to {r[3]:.1f} mm from the top long edge '
                  f'({r[3] - r[1]:.1f} mm wide), from the board surface up to {D.MPT["height"]:.1f} mm; '
                  'leave room above it to turn the screws.')
    md += [f'- **Height:** the terminal blocks are the tallest parts ({D.MPT["height"]:.1f} mm). Allow 12 mm above the '
           'board and 4 mm below it for the solder side and trimmed leads.',
           '- **The module** is held by its 12 soldered pins. A rib in the lid that bears lightly on its far end stops it '
           'rocking in a vibrating car.']
    with open(os.path.join(board_dir, 'ASSEMBLY.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(md) + '\n')


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        h.update(f.read())
    return h.hexdigest()


def manifest_files(board_dir):
    out = []
    for dirpath, dirnames, files in os.walk(board_dir):
        dirnames[:] = sorted(x for x in dirnames if x != '__pycache__')
        for name in sorted(files):
            rel = os.path.relpath(os.path.join(dirpath, name), board_dir)
            if rel not in MANIFEST_SKIP and not name.endswith('.pyc'):
                out.append(rel)
    return sorted(out)


def write_manifest(board_dir):
    lines = [f'{sha256(os.path.join(board_dir, rel))}  {rel}' for rel in manifest_files(board_dir)]
    with open(os.path.join(board_dir, 'outputs.sha256'), 'w', encoding='utf-8') as f:
        f.write(f'# Written by build.sh. tests/test_{N.replace("-", "_")}.py fails if any listed file changes\n'
                '# without a rebuild: regenerate with build.sh, never edit outputs by hand.\n')
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    cmd, args = sys.argv[1], sys.argv[2:]
    {'bom': write_bom, 'assembly': write_assembly, 'manifest': write_manifest}[cmd](*args)
