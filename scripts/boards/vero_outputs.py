"""Write an option's stripboard assembly sheet. Stdlib only.

    python3 vero_outputs.py <a|b> <out_dir>     writes <out_dir>/ASSEMBLY.md

build.sh calls this after vero_draw.py.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import circuit as C  # noqa: E402
import vero as V  # noqa: E402
import vero_layout as L  # noqa: E402


def key(ref):
    m = re.match(r'([A-Za-z]+)(\d*)', ref)
    return m.group(1).upper(), int(m.group(2) or 0)


def hole(h):
    return f'{h[0]},{h[1]}'


def write_assembly(option, out_dir):
    b = V.Board(option)
    a = V.analyse(b)
    if a['problems']:
        raise SystemExit('layout problems:\n' + '\n'.join(a['problems']))
    w, h = b.size_mm()
    P = V.P
    up = option.upper()
    md = [f'# Option {up} stripboard: assembly sheet', '',
          f'Generated by `scripts/boards/vero_outputs.py` from `scripts/boards/vero_layout.py`. Edit the layout, not '
          f'this file, then run `scripts/boards/build.sh`. Holes are written column,strip: columns are counted along '
          f'the strips from the left and strips from the top, with the board component side up as in `layout.svg`.', '',
          '## Board', '',
          f'- **{b.W} holes along the strips by {b.H} strips.** Cut the stripboard along the next line of holes outside '
          f'that (column 0 and {b.W + 1}, strip 0 and {b.H + 1}) and file the edges smooth: **{w:.1f} x {h:.1f} mm**.',
          f'- **{len(b.cuts)} track cuts and {len(b.links)} wire links.**', '',
          '## 1. Track cuts (copper side)', '',
          'Cut each strip at the hole listed, with a spot-face cutter or a 3.5 mm drill turned by hand, until no copper '
          'bridges the hole. The copper side is mirrored: column 1 is on the **right** when the board is turned over.', '',
          '| Strip | Columns |', '|---:|---|']
    by_strip = {}
    for c, s in sorted(b.cuts):
        by_strip.setdefault(s, []).append(c)
    for s in sorted(by_strip):
        md.append(f'| {s} | {", ".join(str(c) for c in by_strip[s])} |')
    md += ['', '## 2. Wire links (component side)', '',
           'Tinned copper wire, flat on the board, fitted before the parts.', '',
           '| Link | From | To | Joins |', '|---|---|---|---|']
    for i, (p, q) in enumerate(b.links):
        net = a['segment_net'][V.segment_of(p, a['cuts'])]
        md.append(f'| L{i + 1} | {hole(p)} | {hole(q)} | {net} |')
    md += ['', '## 3. Parts, lowest first', '',
           'Resistors lie flat with their leads 10.16 mm apart (Vishay asks for at least 10.0 mm between an 0207\'s '
           'leads when it lies flat).', '',
           '| Ref | Value | Holes | Notes |', '|---|---|---|---|']
    order = {'R0207': 0, 'RAD2': 1, 'MPT4': 5, 'module': 6}
    for ref in sorted(b.parts, key=lambda r: (order[b.parts[r][0]], key(r))):
        kind, value, _pmap = b.parts[ref]
        if kind == 'module':
            c, s = L.MODULE_AT['col'], L.MODULE_AT['strip']
            md.append(f'| {ref} | {value} | VIN..!RST down {c},{s}-{c},{s + 5}; Ref+..Ref- down '
                      f'{c + L.ROW_SPACING},{s}-{c + L.ROW_SPACING},{s + 5} | Chip side up, legend reading down the '
                      'board. Solder its 12 header pins straight into the stripboard; never socket it |')
        elif kind.startswith('MPT'):
            hp = V.block_pins(b, ref)
            side = b.blocks[ref][2]
            md.append(f'| {ref} | {value} | pin 1 at {hole(hp["1"])} to pin {len(hp)} at {hole(hp[str(len(hp))])} | '
                      f'Wire entries face the {side} end |')
        else:
            p1, p2 = a['pins'][(ref, '1')], a['pins'][(ref, '2')]
            span = abs(p1[0] - p2[0]) + abs(p1[1] - p2[1])
            way = 'along strip ' + str(p1[1]) if p1[1] == p2[1] else 'across the strips'
            note = f'{way}, {span * P:.2f} mm'
            if ref == 'Rref':
                note += '. Measure it first and put the value in `kReferenceOhms`'
            if kind == 'RAD2':
                note += '. C0G only, never more than 100 nF'
            md.append(f'| {ref} | {value} | {hole(p1)} and {hole(p2)} | {note} |')
    if option == 'a':
        md += ['', 'Option B\'s C1 (13,4 and 13,5) and C2 (15,5 and 15,6) holes stay empty. Fitting C1 and C2 there '
                   'turns this board into option B.']
    md += ['', '## 4. Wiring', '',
           '| Terminal | Pin | Wire |', '|---|---:|---|']
    for pin, what in L.J1_WIRES.items():
        md.append(f'| J1 (display lead) | {pin} | {what} |')
    for pin, what in C.HARNESS_WIRES.items():
        md.append(f'| J2 (sender harness) | {pin} | {what} |')
    md += ['', '## 5. Checks before power', '',
           '- Under a magnifier, check every cut is clean and no solder bridges two strips. No ground strip runs beside '
           'SENSE, SENDER, A1 or A2, so a bridge can\'t join those to ground, but fix any bridge you find.',
           '- With a meter on continuity, and the module not yet powered, check each net joins only its own holes:', '']
    for net, members in sorted(C.nets(b.parts).items()):
        md.append(f'  - **{net}:** ' + ', '.join(f'{r}.{p} ({hole(a["pins"][(r, p)])})'
                                                 for r, p in sorted(members, key=lambda m: (key(m[0]), m[1]))))
    md += ['', '- Then that no two of +3V3, GND, SCL, SDA, AIN0, AIN1, AIN2, SENDER and SENSE are joined.', '',
           '## Box', '',
           f'- **Board:** {w:.1f} x {h:.1f} mm, 1.6 mm thick. Hold it by its two long edges in slots in the box sides '
           f'(about 1 mm deep): nothing on the board comes within {V.EDGE_KEEP:.0f} mm of those edges.']
    for ref in ('J1', 'J2'):
        r = a['bodies'][ref]
        side = b.blocks[ref][2]
        md.append(f'- **{ref} opening, {side} end:** {r[1]:.1f} to {r[3]:.1f} mm from the top long edge '
                  f'({r[3] - r[1]:.1f} mm wide), from the board surface up to {V.MPT["height"]:.1f} mm; leave room '
                  'above it to turn the screws.')
    md += [f'- **Height:** the terminal blocks ({V.MPT["height"]:.1f} mm) and the module on its header '
           f'(about {C.MODULE["height"]:.1f} mm) are the tallest parts. Allow 12 mm above the board and 4 mm below it.',
           '- **The module** is held by its 12 soldered pins. A rib in the lid that bears lightly on it stops it rocking '
           'in a vibrating car.']
    with open(os.path.join(out_dir, 'ASSEMBLY.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(md) + '\n')


if __name__ == '__main__':
    write_assembly(sys.argv[1], sys.argv[2])
